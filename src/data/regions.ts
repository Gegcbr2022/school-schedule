/**
 * Івано-Франківська — там, де стоїть школа, з якої все почалось. Це
 * значення за замовчуванням, а не єдине можливе.
 */
export const DEFAULT_REGION = '13'

/** Область або район за ключем. */
export function placeByKey(key: string): Place | undefined {
  const uid = Number(key)
  if (!Number.isFinite(uid)) return undefined
  for (const oblast of OBLASTS) {
    if (oblast.uid === uid) return oblast
    const raion = oblast.raions.find((r) => r.uid === uid)
    if (raion) return raion
  }
  return undefined
}

/** Область, у якій лежить обране, — для другого списку в налаштуваннях. */
export function oblastOfKey(key: string): Oblast | undefined {
  const uid = Number(key)
  return OBLASTS.find((o) => o.uid === uid || o.raions.some((r) => r.uid === uid))
}

/** Ключ регіону, якщо такий регіон узагалі є. */
export function knownRegion(value: unknown): string | null {
  return typeof value === 'string' && placeByKey(value) !== undefined ? value : null
}
