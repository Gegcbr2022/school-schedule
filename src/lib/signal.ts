/**
 * Те, чим сайт може попередити про тривогу без жодного сервера.
 *
 * ЧОГО У ВЕБА НЕМАЄ. Живих активностей — не існує такого API взагалі.
 * Локальних нагадувань за розкладом — теж: браузер не вміє «розбудити
 * мене о 7:45», і жодна обіцянка цього не змінить. Справжні пуші
 * технічно можливі (iOS 16.4+ для встановленого PWA), але це сервер із
 * токенами пристроїв, тобто база з людьми, — а її тут свідомо немає.
 *
 * ЩО ЗАЛИШАЄТЬСЯ. Дві дрібниці, які нічого не коштують і працюють:
 *
 *   · **Значок на іконці.** Встановлений PWA уміє показати крапку —
 *     рівно те, що треба, щоб побачити тривогу, не відкриваючи нічого.
 *   · **Заголовок вкладки.** Учитель тримає розклад відкритим у
 *     ноутбуці; підписана вкладка помітна боковим зором.
 *
 * Обидва звуться «сигналом», а не «сповіщенням», навмисно: вони
 * працюють, лише поки застосунок відкритий або встановлений, і нічого
 * не обіцяють тому, хто його закрив.
 */

/** Назва, до якої повертаємось, коли тривоги немає. */
const PLAIN = 'Дзвінка — розклад уроків'

type Badger = Navigator & {
  setAppBadge?: (count?: number) => Promise<void>
  clearAppBadge?: () => Promise<void>
}

export function signalAlert(level: number, title: string): void {
  const nav = navigator as Badger

  try {
    if (level > 0) void nav.setAppBadge?.(1)
    else void nav.clearAppBadge?.()
  } catch {
    /* Значків немає — і не треба. */
  }

  // Кружечок, а не слово: у вузькій вкладці видно тільки перші знаки.
  const mark = level >= 2 ? '🔴' : '🟡'
  document.title = level > 0 ? `${mark} ${title}` : PLAIN
}
