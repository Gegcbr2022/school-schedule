/**
 * Не дає зібрати iOS-застосунок, який ніколи не оновить розклад.
 *
 * Уся будова з паком існує заради однієї речі: щоб перенесений урок
 * доїжджав до телефонів, не чекаючи перевірки Apple. Але за
 * замовчуванням застосунок шукає розклад «поруч із собою», а поруч із
 * ним — той самий файл із пакета: версія завжди та сама, свіжішого не
 * буває ніколи. Збірка виходить зовні справною й мовчки непридатною.
 *
 * Тому адресу треба назвати вголос. Для збірки, яку справді не треба
 * оновлювати (перевірити верстку на симуляторі), є `VITE_PACK_URL=bundle`.
 */

const url = process.env.VITE_PACK_URL

if (!url) {
  console.error(
    `
Не вказано VITE_PACK_URL — звідки застосунок братиме розклад.

Без нього він шукатиме розклад усередині себе, і оновлення не прийде
ніколи: щоб виправити урок, доведеться випускати нову версію в App Store.

  VITE_PACK_URL=https://gegcbr2022.github.io/school-schedule/data/school.json npm run build:ios

Якщо це разова збірка для симулятора й оновлення не потрібні:

  VITE_PACK_URL=bundle npm run build:ios
`.trim(),
  )
  process.exit(1)
}

if (url === 'bundle') {
  console.warn('УВАГА: збірка без оновлення розкладу — лише для перевірки на симуляторі.')
  process.exit(0)
}

if (!URL.canParse(url) || !/^https?:$/.test(new URL(url).protocol)) {
  console.error(`VITE_PACK_URL має бути повною адресою http(s), а не «${url}».`)
  process.exit(1)
}
