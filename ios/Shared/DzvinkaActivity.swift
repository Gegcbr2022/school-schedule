import ActivityKit
import Foundation

/// Що «Дзвінка» показує на екрані блокування й у динамічному острові.
///
/// Файл спільний для застосунку й розширення віджетів: один оголошує
/// активність, другий її малює, і розійтись вони не можуть — у
/// `ActivityKit` розбіжність у полях означає мовчазну відмову
/// запускатись, без жодної помилки.
///
/// Рахувати час тут нічого: `deadline` — це момент, до якого йде відлік,
/// а сам відлік малює система (`Text(timerInterval:)`). Саме тому
/// активність не потребує оновлень щохвилини: цифри біжать самі, а ми
/// доторкаємось до неї лише на межі уроку.
struct DzvinkaActivity: ActivityAttributes {
  struct ContentState: Codable, Hashable {
    /// «Зараз 3 урок», «Перерва», «До початку».
    var headline: String
    /// «Математика», «Далі: українська мова».
    var subject: String
    /// «каб. 12». Порожньо — у розкладі кабінету немає.
    var room: String
    /// «Далі: Математика · каб. 18» — дрібним сірим під усім іншим.
    var next: String
    /// Момент, до якого йде відлік. `nil` — відліку немає.
    var deadline: Date?
    /// Початок нинішнього відрізка — з нього малюється смужка прогресу.
    var since: Date?
    /// Рівень повітряної тривоги; 0 — тривоги немає.
    var alert: Int
    /// Підпис під тривогою: «Івано-Франківська область».
    var alertNote: String
    /**
     * Чий це розклад.
     *
     * САМЕ В СТАНІ, А НЕ В АТРИБУТАХ. Атрибути `ActivityKit` заморожує
     * на весь час життя активності — змінити їх не можна взагалі. А в
     * батьків із двома дітьми профіль перемикається по кілька разів на
     * день, і ім'я на екрані блокування лишалося б від першої дитини
     * поруч з уроком другої.
     */
    var profileName: String

    /// Триває тривога — і тоді вона головніша за будь-який урок.
    var underAlert: Bool { alert > 0 }
  }

  /**
   * Атрибутів немає навмисно: усе, що показує активність, міняється
   * протягом дня, а змінюваним у `ActivityKit` є лише стан.
   */
  var kind = "schedule"
}

/// Рівні повітряної тривоги — ті самі, що з 5 вересня 2026 року
/// оголошують офіційно (постанова КМУ №1092).
///
/// Жовтий і червоний — не «слабка» й «сильна» тривога, а різні дії:
/// на жовтому школа може працювати за наявності укриття, на червоному
/// в укриття йдуть усі. Тому рівень має бути видно з першого погляду,
/// а не читатися дрібним рядком.
enum AlertLevel {
  static let none = 0
  /// Жовтий: загроза БпЛА.
  static let yellow = 1
  /// Червоний: ракетна небезпека, балістика, масований удар.
  static let red = 2

  static func title(_ level: Int) -> String {
    switch level {
      case red: return "Червоний рівень"
      case yellow: return "Жовтий рівень"
      default: return ""
    }
  }

  static func detail(_ level: Int) -> String {
    switch level {
      case red: return "Ракетна небезпека — в укриття"
      case yellow: return "Загроза БпЛА"
      default: return ""
    }
  }
}
